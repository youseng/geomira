/**
 * The PWA part of the site build (Run 12, SPEC §1 v1.1): after Vite has written `dist`, this
 * plugin lists the build's files, derives the version from their contents, and writes `sw.js`
 * (src/sw/service-worker.ts with that list, the cache name and the build id filled in). Not used
 * by the single-file build, which a browser cannot run a service worker for (file://).
 */
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { transformWithEsbuild, type Plugin } from 'vite';

export const SW_FILE = 'sw.js';

/** Files of the build that are not precached: source maps and the worker script itself. */
export function precacheList(files: readonly string[]): string[] {
  return files
    .filter((f) => !f.endsWith('.map') && f !== SW_FILE)
    .slice()
    .sort();
}

/** The version of a build: a hash of every precached file's path and bytes (12 hex digits). */
export function contentVersion(files: readonly { path: string; bytes: Uint8Array }[]): string {
  const h = createHash('sha256');
  for (const f of [...files].sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0))) {
    h.update(f.path);
    h.update('\0');
    h.update(f.bytes);
    h.update('\0');
  }
  return h.digest('hex').slice(0, 12);
}

/** Every file under `dir`, as paths relative to it with forward slashes. */
export function listFiles(dir: string): string[] {
  const out: string[] = [];
  const walk = (d: string) => {
    for (const name of readdirSync(d)) {
      const p = join(d, name);
      if (statSync(p).isDirectory()) walk(p);
      else out.push(relative(dir, p).split(sep).join('/'));
    }
  };
  walk(dir);
  return out;
}

/** The service worker's script for a build: the template with its constants defined. */
export async function serviceWorkerScript(
  template: string,
  cfg: { precache: readonly string[]; cache: string; build: string },
): Promise<string> {
  const out = await transformWithEsbuild(template, 'service-worker.ts', {
    format: 'iife',
    target: 'es2020',
    define: {
      __GEOMIRA_PRECACHE__: JSON.stringify(cfg.precache),
      __GEOMIRA_CACHE__: JSON.stringify(cfg.cache),
      __GEOMIRA_BUILD__: JSON.stringify(cfg.build),
    },
  });
  return `// Geomira service worker, build ${cfg.build} (generated by apps/web/build/pwa.ts)\n${out.code}`;
}

/** Writes `sw.js` into the output directory once the bundle is written. */
export function pwaPlugin(opts: { template: string; build: string }): Plugin {
  let outDir = 'dist';
  return {
    name: 'geomira-pwa',
    apply: 'build',
    configResolved(config) {
      outDir = config.build.outDir.startsWith('/')
        ? config.build.outDir
        : join(config.root, config.build.outDir);
    },
    async closeBundle() {
      const precache = precacheList(listFiles(outDir));
      const version = contentVersion(
        precache.map((path) => ({ path, bytes: readFileSync(join(outDir, path)) })),
      );
      const code = await serviceWorkerScript(readFileSync(opts.template, 'utf8'), {
        precache,
        cache: `geomira-${version}`,
        build: opts.build,
      });
      writeFileSync(join(outDir, SW_FILE), code);
    },
  };
}
