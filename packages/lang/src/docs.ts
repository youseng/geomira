export function renderLanguageDocs(registry: Registry): string {
  const migrations =
    MIGRATIONS.length === 0
      ? 'none (version 1 is the first)'
      : MIGRATIONS.map((m) => `${String(m.from)} → ${String(m.to)} (${m.describe})`).join('; ');
  const out = [
    ...intro(),
    ...notation(),
    ...geomdrawSection(registry),
    '## Tools',
    '',
    'Exactness is observed by running each tool\'s examples over RationalField: "can succeed" means some example is exact (otherwise the reason it is not); the last column gives the reason of each example that is Inexact over Q (√ or trigonometry off the rational values).',
    '',
    ...tools(registry),
    '',
    '## Versions',
    '',
    `Current version: ${String(DOCUMENT_VERSION)}. Migrations: ${migrations}.`,
  ];
  return `${out.join('\n')}\n`;
}
