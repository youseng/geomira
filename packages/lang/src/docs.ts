/** The reasons of the examples that are Inexact over RationalField (the observed gaps). */
function gaps(registry: Registry, t: ToolSpec): string {
  const reasons = t.examples.flatMap((e) => {
    const v = runExample(registry, t, e, RationalField);
    return v.kind === 'inexact' ? [v.reason] : [];
  });
  return [...new Set(reasons)].join('; ') || '—';
}

function tools(registry: Registry): string[] {
  const rows = registry.tools.map((t) => [
    `\`${t.name}\``,
    t.family,
    t.signatures.map((s) => `\`${formatSignature(t.name, s)}\``).join(' · '),
    t.outputKinds.join(', '),
    exactness(registry, t),
    gaps(registry, t),
  ]);
  return table(
    ['tool', 'family', 'signatures', 'result', 'exact run (RationalField)', 'Inexact examples'],
    rows,
  );
}

function claims(): string[] {
  const rows = CLAIM_KINDS.map((k) => {
    const n = CLAIM_NOTATION.find((x) => x.kind === k.name);
    return [
      `\`${k.name}\``,
      (n?.forms ?? []).map((f) => `\`${f}\``).join(', '),
      `\`${n?.example ?? ''}\``,
      k.polynomial ? 'yes' : 'no',
    ];
  });
  return table(['kind', 'notation', 'example', 'polynomial'], rows);
}

